import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

# ─────────────────────────────────────────────────────────────────────────────
# Internal helpers
# ─────────────────────────────────────────────────────────────────────────────

_EVAL_DIR    = Path(__file__).resolve().parent
_BOT_DIR     = _EVAL_DIR.parent / "Bot"

def _make_agent_workspace(
    workspace: Path,
    stripped_binary: Path,
    stripped_decompiled_c: Path,
) -> Path:
    agent_dir = workspace / "agent_bot"
    if agent_dir.exists():
        shutil.rmtree(agent_dir)
    agent_dir.mkdir(parents=True)

    # Do NOT copy previous run caches/dbs from the main Bot folder
    ignore_files = {"triage_cache.json", "analysis_state.json", "state.db", "global_data.json"}
    
    for item in _BOT_DIR.iterdir():
        if item.name in ignore_files:
            continue
        if item.suffix in (".py", ".java", ".json", ".txt", ".c"):
            shutil.copy2(item, agent_dir / item.name)

    dyn_global_json = stripped_decompiled_c.with_name(stripped_decompiled_c.stem + "_global_data.json")

    # Import the guaranteed absolute path from your eval config
    from eval_config import GHIDRA_PATH as EVAL_GHIDRA_PATH

    patched_config = f"""# AUTO-GENERATED by eval/agent_runner.py
import os
from dotenv import load_dotenv
from google import genai
from google.genai import types

load_dotenv()

# Hardcode the absolute path so the nested agent doesn't get lost
GHIDRA_PATH  = "{str(Path(EVAL_GHIDRA_PATH).resolve()).replace(chr(92), '/')}"
PROJECT_DIR  = "{str((workspace / 'ghidra_agent').resolve()).replace(chr(92), '/')}"
PROJECT_NAME = "EvalAgent"

TARGET_BINARY = "{str(stripped_binary.resolve()).replace(chr(92), '/')}"
OUTPUT_C      = "{str(stripped_decompiled_c.resolve()).replace(chr(92), '/')}"
STATE_FILE    = "{str((agent_dir / 'analysis_state.json').resolve()).replace(chr(92), '/')}"
CHECKPOINT_DB = "{str((agent_dir / 'state.db').resolve()).replace(chr(92), '/')}"
STRINGS_JSON  = "{str((agent_dir / 'function_strings.json').resolve()).replace(chr(92), '/')}"
TRIAGE_CACHE  = "{str((agent_dir / 'triage_cache.json').resolve()).replace(chr(92), '/')}"
GLOBAL_DATA_JSON = "{str(dyn_global_json.resolve()).replace(chr(92), '/')}"

client = genai.Client(api_key=os.environ.get("GEMINI_API_KEY"))
"""
    (agent_dir / "config.py").write_text(patched_config)

    import time
    thread_id = f"eval_run_{int(time.time())}"

    main_eval = f"""# AUTO-GENERATED by eval/agent_runner.py
import sys
import json
from pathlib import Path
sys.path.insert(0, str(Path(__file__).parent))

from langgraph.graph import StateGraph, END
from langgraph.checkpoint.sqlite import SqliteSaver

from config import CHECKPOINT_DB, STATE_FILE
from state import REState
from node_ingestion import ingestion_node
from node_triage    import triage_node
from node_planner   import planner_node
from node_analyst   import analyst_node
from node_dynamic   import dynamic_node

builder = StateGraph(REState)
builder.add_node("ingestor", ingestion_node)
builder.add_node("triager",  triage_node)
builder.add_node("planner",  planner_node)
builder.add_node("analyst",  analyst_node)
builder.add_node("dynamic",  dynamic_node)

builder.set_entry_point("ingestor")
builder.add_edge("ingestor", "triager")
builder.add_edge("triager",  "planner")

def analyst_router(state: REState):
    target = state["current_target"]
    if state["functions"][target]["status"] == "OBFUSCATED":
        return "dynamic"
    return "planner"

builder.add_conditional_edges("analyst", analyst_router, {{"dynamic": "dynamic", "planner": "planner"}})
builder.add_edge("dynamic", "planner")
builder.add_conditional_edges(
    "planner",
    lambda x: "end" if x["phase"] == "end" else "continue",
    {{"end": END, "continue": "analyst"}},
)

if __name__ == "__main__":
    with SqliteSaver.from_conn_string(CHECKPOINT_DB) as saver:
        graph = builder.compile(checkpointer=saver)
        run_config = {{"configurable": {{"thread_id": "{thread_id}"}}}}
        initial_state = {{
            "functions": {{}}, "symbol_table": {{}}, "current_target": "",
            "suggested_target": "", "call_graph": {{}}, "history": [], "phase": "start",
        }}
        
        for event in graph.stream(initial_state, config=run_config):
            for node, output in event.items():
                print(f"\\n>>> [{{node.upper()}} COMPLETED]")
                for k, v in output.items():
                    if k == "functions":
                        print(f"    functions: <dict with {{len(v)}} items>")
                    elif k == "symbol_table":
                        print(f"    symbol_table: <dict with {{len(v)}} items>")
                    elif k == "history":
                        print(f"    latest history: {{v[-1] if v else 'None'}}")
                    else:
                        print(f"    {{k}}: {{v}}")
                        
        final_state = graph.get_state(run_config).values
        with open(STATE_FILE, "w", encoding="utf-8") as f:
            json.dump(final_state, f, indent=2, default=str)
            
    print("\\n[agent] Run complete. State exported to", STATE_FILE)
"""

    (agent_dir / "main_eval.py").write_text(main_eval)
    return agent_dir

# ─────────────────────────────────────────────────────────────────────────────
# Public API
# ─────────────────────────────────────────────────────────────────────────────

def run_agent(
    workspace:            str | Path,
    stripped_binary:      str | Path,
    stripped_decompiled_c: str | Path,
    python_executable:    str = sys.executable,
) -> dict:
    workspace             = Path(workspace).resolve()
    stripped_binary       = Path(stripped_binary).resolve()
    stripped_decompiled_c = Path(stripped_decompiled_c).resolve()

    print("\n" + "="*60)
    print("[agent_runner] Setting up isolated Bot workspace …")
    agent_dir = _make_agent_workspace(
        workspace, stripped_binary, stripped_decompiled_c
    )

    state_file = agent_dir / "analysis_state.json"
    main_script = agent_dir / "main_eval.py"

    print("[agent_runner] Launching REtard agent …")
    print("="*60 + "\n")

    result = subprocess.run(
        [python_executable, str(main_script)],
        cwd=str(agent_dir),
        env={**os.environ},   
    )

    print("\n" + "="*60)

    if result.returncode != 0:
        raise RuntimeError(f"REtard agent exited with code {result.returncode}.")

    if not state_file.exists():
        raise FileNotFoundError(f"Agent finished but {state_file} was not created.")

    with open(state_file, "r", encoding="utf-8") as f:
        agent_output = json.load(f)

    symbol_table = agent_output.get("symbol_table", {})
    functions    = agent_output.get("functions",    {})

    print(f"[agent_runner] ✔  Agent complete.")
    print(f"               Symbol table entries : {len(symbol_table)}")
    print(f"               Functions processed  : {len(functions)}")

    return {
        "symbol_table": symbol_table,
        "functions":    functions,
    }
